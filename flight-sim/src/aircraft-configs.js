// Flap position as the pilot knows it: detent labels (737 UP/1/5…, A320 CONF 0/1/1+F…) or degrees.
export function flapText(cfg, v) {
	if (cfg.flapLabels) {
		let bi = 0;
		cfg.flapDetents.forEach((d, i) => { if (Math.abs(d - v) < Math.abs(cfg.flapDetents[bi] - v)) bi = i; });
		return (cfg.id === 'a320' ? 'CONF ' : '') + cfg.flapLabels[bi];
	}
	return `${Math.round(v * (cfg.flapMaxDeg || 30))}°`;
}
